# Day 5-6: Lists, Tuples, Sets, Dictionaries

# Lists
fruits = ["apple", "banana", "cherry"]
print(fruits)
fruits.append("orange")
print(fruits[1])

# Tuples
tuple1 = (1, 2, 3)
print(tuple1)
print(tuple1[0])

# Sets
set1 = {1, 2, 3, 2}
print(set1)
set1.add(4)

# Dictionaries
d = {"name": "Alice", "age": 25}
print(d)
print(d["name"])
d["city"] = "New York"
print(d)
